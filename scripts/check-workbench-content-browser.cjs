'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { promisify } = require('node:util');
const execFile = promisify(require('node:child_process').execFile);
const { chromium, expect } = require('@playwright/test');
const { startServer } = require('../workbench/scripts/workbench.cjs');

async function main() {
  const directory = path.resolve('.qa/workbench-content-browser', `run-${Date.now()}`);
  const task = path.join(directory, 'task');
  fs.mkdirSync(directory, {recursive:true});
  const app = await startServer({taskDirectory:task});
  const browser = await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || (process.platform==='win32'?'C:/Program Files/Google/Chrome/Application/chrome.exe':undefined),headless:true});
  const result = {directory,checks:[],errors:[]};
  const context = await browser.newContext({viewport:{width:1440,height:900},permissions:['clipboard-read','clipboard-write']});
  const page = await context.newPage();
  page.setDefaultTimeout(12000);
  page.on('pageerror',error=>result.errors.push(error.message));
  const check = name=>result.checks.push(name);
  const state = ()=>fetch(app.url+'/api/workbench/state').then(r=>r.json());
  const content = async payload=>{
    const current=await state();
    const response=await fetch(app.url+'/api/workbench/content',{method:'POST',headers:{Origin:app.url,'Content-Type':'application/json','X-Workbench-Id':current.workspaceId},body:JSON.stringify({requestId:require('node:crypto').randomUUID(),nodeId:'validate',baseContentRevision:current.contentTree.revision,...payload})});
    const value=await response.json();assert.equal(response.status,200,JSON.stringify(value));return value;
  };
  const cli = async (...args)=>JSON.parse((await execFile(process.execPath,[path.resolve('workbench/scripts/workbench.cjs'),...args,'--task',task],{encoding:'utf8'})).stdout);
  const list = page.getByTestId('node-content-panel');
  const panel = list.locator('[data-content-node-id="validate"]');
  const form = ()=>page.getByTestId('content-composer');
  try {
    await page.goto(app.url);
    await expect(page.getByTestId('node-inspector')).toHaveCount(0);
    await page.getByTestId('graph-node-validate').click();
    await expect(page.getByTestId('node-title')).toHaveText('校验降幅');
    const baseline = await state();
    await page.getByTestId('view-node-materials').click();await panel.getByTestId('add-content-note').click();
    await expect(page.getByTestId('quick-content')).toHaveCount(0);await expect(panel).toBeVisible();
    await expect(page.getByTestId('graph-canvas')).toBeHidden();
    await expect(form().getByLabel('补充原话',{exact:true})).toBeFocused();
    await expect(form().getByLabel('补充标题',{exact:true})).toBeHidden();
    await expect(form().getByLabel('所属栏目',{exact:true})).toBeHidden();
    await expect(form().getByLabel('补充性质',{exact:true})).toBeHidden();
    await form().getByLabel('补充原话',{exact:true}).fill(' \n\t');
    await expect(form().getByTestId('save-content')).toBeDisabled();
    await form().getByLabel('补充原话',{exact:true}).fill('录入时不要漏填币种。');
    await page.screenshot({path:path.join(directory,'01-quick.png'),fullPage:false});
    await expect(page.getByTestId('edit-copy')).toHaveCount(0);
    await expect(panel).toBeVisible();
    await expect(panel.getByTestId('node-prose-validate')).toContainText(baseline.model.claims.find(c=>c.id==='validate-actions').text);
    await expect(page.getByTestId('node-inspector')).toHaveCount(0);
    await expect(page.getByTestId('workspace-node-title')).toHaveText('校验降幅');
    await expect(form().getByLabel('补充原话',{exact:true})).toHaveValue('录入时不要漏填币种。');
    await form().getByTestId('save-content').click();
    await expect(form()).toBeHidden();
    await expect(page.getByTestId('node-inspector')).toHaveCount(0);
    await expect(panel.locator('.workspace-current-result')).not.toContainText('录入时不要漏填币种。');
    const first=(await state()).contentTree.entries.at(-1);
    assert.equal(first.kind,'raw');assert.equal(first.title,'');assert.equal(first.parentId,null);
    check('Graph enters the selected node wide workspace; result and materials stay separate without a duplicate drawer');

    const splitReview = panel.getByRole('button', { name: '核对节点拆分' });
    await splitReview.click();
    await expect(page.getByTestId('agent-task-targets')).toContainText('校验降幅');
    await expect(page.getByTestId('agent-task-text')).toHaveValue(/各自启动/);
    await expect(page.getByTestId('agent-task-materials')).toContainText(baseline.model.sources[0].name);
    await page.getByTestId('cancel-agent-task').click();
    await expect(splitReview).toBeFocused();
    check('Node split review opens with the selected node and its source materials');

    // Existing classified records remain readable/editable, but new material
    // entry no longer makes users choose a section or semantic category.
    await content({operation:'create',entryType:'section',title:'平台差异'});
    const section = (await state()).contentTree.entries.find(e=>e.title==='平台差异');
    await content({operation:'create',entryType:'note',kind:'reminder',title:'旧录入提醒',parentId:section.id,text:'渠道 A 容易忘记备注。'});
    const legacy=(await state()).contentTree.entries.at(-1);
    await expect(panel.locator(`[data-content-id="${legacy.id}"]`)).toBeVisible();
    await panel.locator(`[data-content-id="${legacy.id}"]`).getByRole('button',{name:'修订原话',exact:true}).click();
    await form().getByLabel('补充原话',{exact:true}).fill('渠道 A 容易忘记备注，请留意。');
    await form().getByTestId('save-content').click();
    await expect(form()).toBeHidden();
    await page.reload();
    await expect(panel.locator('.content-entry-text').filter({hasText:'渠道 A'})).toBeVisible();
    await page.getByTestId('view-graph').click();
    await page.getByTestId('graph-node-validate').click();
    await expect(page.getByTestId('node-inspector')).not.toContainText('渠道 A');await page.getByTestId('view-node-materials').click();await expect(panel.locator('.content-entry-text').filter({hasText:'渠道 A'})).toBeVisible();await page.getByTestId('view-graph').click();
    assert.equal((await state()).modelHash,baseline.modelHash);
    assert.equal((await state()).workRevision,baseline.workRevision);
    const retained=(await state()).contentTree.entries.find(e=>e.id===legacy.id);
    assert.equal(retained.kind,'reminder');assert.equal(retained.title,'旧录入提醒');assert.equal(retained.parentId,section.id);assert.equal(retained.revisions[0].text,'渠道 A 容易忘记备注。');
    check('Existing section/classification/title and original history survive simple text editing without changing model or W');

    await page.getByTestId('view-node-materials').click();await panel.getByTestId('add-content-note').click();
    await form().getByLabel('补充原话',{exact:true}).fill('服务已保存但响应丢失的原话。');
    let applied;
    await page.route('**/api/workbench/content',async route=>{applied=await route.fetch();await route.abort('failed');},{times:1});
    await form().getByTestId('save-content').click();
    await expect(page.getByTestId('retry-content-save')).toBeVisible();
    assert.equal(applied.status(),200);
    await page.reload();
    await expect(page.getByTestId('retry-content-save')).toBeVisible();
    await page.getByTestId('retry-content-save').click();
    await expect(form()).toBeHidden();
    assert.equal((await state()).contentTree.entries.filter(e=>e.text==='服务已保存但响应丢失的原话。').length,1);
    check('Lost response and reload retry exactly the original save without duplicate notes');

    await page.getByTestId('view-content').click();
    await panel.getByTestId('add-content-note').click();
    await form().getByLabel('补充原话',{exact:true}).fill('这一步现在由财务专员负责。');
    await form().getByTestId('save-content').click();
    await expect(form()).toBeHidden();
    const fact=(await state()).contentTree.entries.at(-1);
    await panel.getByTestId('refine-node-materials').click();
    await expect(page.getByTestId('agent-task-materials')).toContainText(baseline.model.sources[0].name);
    await page.getByTestId('cancel-agent-task').click();
    await panel.getByTestId('refine-node-materials').click();
    await page.getByTestId('confirm-agent-task').click();
    await expect(page.getByTestId('agent-task-preview')).toBeHidden();
    await expect.poll(()=>page.evaluate(()=>navigator.clipboard.readText())).toContain('process-review-workbench-ref:v1 ');
    const handoff=await page.evaluate(()=>navigator.clipboard.readText());
    const marker='process-review-workbench-ref:v1 ';
    const header=JSON.parse(handoff.slice(handoff.indexOf(marker)+marker.length).split('\n')[0]);
    const reference=await cli('reference',header.referenceId);
    assert.ok(reference.contentInputs.some(e=>e.id===fact.id&&e.kind==='raw'&&e.text===fact.text));
    assert.ok(reference.contentInputs.some(e=>e.kind==='reminder'));
    const candidate=await cli('candidate','--reference',header.referenceId);
    assert.equal(candidate.feedbackSources.length,0);
    assert.ok(candidate.rawMaterialSources.some(source=>source.text===fact.text));
    const model=JSON.parse(fs.readFileSync(candidate.modelFile,'utf8'));
    const source=candidate.rawMaterialSources.find(source=>source.text===fact.text);
    model.sources.push(source);
    const claim={id:'attached-role',text:'财务专员',origin:'explicit',evidence:[{sourceId:source.id,startLine:1,endLine:1,quote:source.text}]};
    model.claims.push(claim);
    model.coverage.push({sourceId:source.id,startLine:1,endLine:1,disposition:'represented',claimIds:[claim.id],issueIds:[],reason:'合成任务中的用户明确更正'});
    const node=model.nodes.find(n=>n.id==='validate');node.claimIds.push(claim.id);node.fields.role=[claim.id];
    fs.writeFileSync(candidate.modelFile,JSON.stringify(model));
    const review=await cli('review-candidate',candidate.candidateId);
    assert.ok(review.changes.length);
    await cli('apply',candidate.candidateId,'--confirm',review.reviewHash);
    await expect(panel.locator(`[data-content-id="${fact.id}"]`)).toContainText('已用于当前结果');
    await expect(panel.locator('.workspace-current-result')).not.toContainText(fact.text);
    await expect(panel.locator('[data-node-section="role"]')).toContainText('财务专员');
    await expect(page.getByTestId('node-inspector')).toHaveCount(0);
    await page.getByTestId('view-graph').click();
    await expect(page.locator('.react-flow__node[data-id="validate"] .node-eyebrow')).toContainText('财务专员');
    const adopted=await state();assert.deepEqual(adopted.model.issues,baseline.model.issues);assert.deepEqual(adopted.model.sources[0],baseline.model.sources[0]);
    assert.equal(adopted.contentTree.entries.find(e=>e.id===fact.id).text,fact.text);
    check('UI handoff → actual CLI source snapshot → review/apply updates node and preserves original input, source and unknowns');

    await page.setViewportSize({width:390,height:844});
    await page.getByTestId('view-content').click();await panel.getByTestId('add-content-note').click();
    await expect(page.getByTestId('quick-content')).toHaveCount(0);await expect(panel).toBeVisible();
    await form().getByLabel('补充原话',{exact:true}).fill('窄屏尚未保存原话。');
    await page.screenshot({path:path.join(directory,'02-narrow-quick.png'),fullPage:false});
    const overflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
    assert.ok(overflow.scroll<=overflow.width+1,JSON.stringify(overflow));
    await page.getByTestId('view-graph').click();
    if(!(await page.getByTestId('node-inspector').count()))await page.getByRole('button',{name:'打开节点详情',exact:true}).click();
    await expect(page.getByTestId('node-inspector')).not.toContainText('窄屏尚未保存原话');
    await page.reload();
    await page.getByTestId('view-content').click();await panel.getByTestId('add-content-note').click();
    await expect(form().getByLabel('补充原话',{exact:true})).toHaveValue('窄屏尚未保存原话。');
    check('Narrow material input is reachable, survives graph/list and reload, and stays outside generated reading');
    assert.deepEqual(result.errors,[]);
    result.passed=true;
  } catch(error) {
    result.failure=error.stack||String(error);result.passed=false;
    await page.screenshot({path:path.join(directory,'failure.png'),fullPage:false}).catch(()=>{});
  } finally {
    fs.writeFileSync(path.join(directory,'result.json'),JSON.stringify(result,null,2));
    fs.writeFileSync(path.resolve('.qa/workbench-content-browser/latest.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify(result,null,2));
    await browser.close();await app.close();
    if(!result.passed)process.exitCode=1;
  }
}
main().catch(error=>{console.error(error);process.exitCode=1;});
